namespace System.Text.Yaml.Serialization.Metadata
{
    /// <summary>
    /// Contains utilities and combinators acting on <see cref="IYamlTypeInfoResolver"/>.
    /// </summary>
    public static class YamlTypeInfoResolver
    {
        /// <summary>
        /// Combines multiple <see cref="IYamlTypeInfoResolver"/> sources into one.
        /// </summary>
        /// <param name="resolvers">Sequence of contract resolvers to be queried for metadata.</param>
        /// <returns>A <see cref="IYamlTypeInfoResolver"/> combining results from <paramref name="resolvers"/>.</returns>
        /// <exception cref="ArgumentException"><paramref name="resolvers"/> is null.</exception>
        /// <remarks>
        /// The combined resolver will query each of <paramref name="resolvers"/> in the specified order,
        /// returning the first result that is non-null. If all <paramref name="resolvers"/> return null,
        /// then the combined resolver will also return <see langword="null"/>.
        ///
        /// Can be used to combine multiple <see cref="YamlSerializerContext"/> sources,
        /// which typically define contract metadata for small subsets of types.
        /// It can also be used to fall back to <see cref="DefaultYamlTypeInfoResolver"/> wherever necessary.
        /// </remarks>
        public static IYamlTypeInfoResolver Combine(params IYamlTypeInfoResolver?[] resolvers)
        {
            ArgumentNullException.ThrowIfNull(resolvers);

            return Combine((ReadOnlySpan<IYamlTypeInfoResolver?>)resolvers);
        }

        /// <summary>
        /// Combines multiple <see cref="IYamlTypeInfoResolver"/> sources into one.
        /// </summary>
        /// <param name="resolvers">Sequence of contract resolvers to be queried for metadata.</param>
        /// <returns>A <see cref="IYamlTypeInfoResolver"/> combining results from <paramref name="resolvers"/>.</returns>
        /// <remarks>
        /// The combined resolver will query each of <paramref name="resolvers"/> in the specified order,
        /// returning the first result that is non-null. If all <paramref name="resolvers"/> return null,
        /// then the combined resolver will also return <see langword="null"/>.
        ///
        /// Can be used to combine multiple <see cref="YamlSerializerContext"/> sources,
        /// which typically define contract metadata for small subsets of types.
        /// It can also be used to fall back to <see cref="DefaultYamlTypeInfoResolver"/> wherever necessary.
        /// </remarks>
        public static IYamlTypeInfoResolver Combine(params ReadOnlySpan<IYamlTypeInfoResolver?> resolvers)
        {
            var resolverChain = new YamlTypeInfoResolverChain();
            foreach (IYamlTypeInfoResolver? resolver in resolvers)
            {
                resolverChain.AddFlattened(resolver);
            }

            return resolverChain.Count == 1 ? resolverChain[0] : resolverChain;
        }

        /// <summary>
        /// Creates a resolver applies modifications to the metadata generated by the source <paramref name="resolver"/>.
        /// </summary>
        /// <param name="resolver">The source resolver generating <see cref="YamlTypeInfo"/> metadata.</param>
        /// <param name="modifier">The delegate modifying non-null <see cref="YamlTypeInfo"/> results.</param>
        /// <returns>A new <see cref="IYamlTypeInfoResolver"/> instance applying the modifications.</returns>
        /// <remarks>
        /// This method is closely related to <see cref="DefaultYamlTypeInfoResolver.Modifiers"/> property
        /// extended to arbitrary <see cref="IYamlTypeInfoResolver"/> instances.
        /// </remarks>
        public static IYamlTypeInfoResolver WithAddedModifier(this IYamlTypeInfoResolver resolver, Action<YamlTypeInfo> modifier)
        {
            ArgumentNullException.ThrowIfNull(resolver);
            ArgumentNullException.ThrowIfNull(modifier);

            return resolver is YamlTypeInfoResolverWithAddedModifiers resolverWithModifiers
                ? resolverWithModifiers.WithAddedModifier(modifier)
                : new YamlTypeInfoResolverWithAddedModifiers(resolver, new[] { modifier });
        }

        /// <summary>
        /// Gets a resolver that returns null <see cref="YamlTypeInfo"/> for every type.
        /// </summary>
        internal static IYamlTypeInfoResolver Empty { get; } = new EmptyYamlTypeInfoResolver();

        /// <summary>
        /// Indicates whether the metadata generated by the current resolver
        /// are compatible with the run time specified <see cref="YamlSerializerOptions"/>.
        /// </summary>
        internal static bool IsCompatibleWithOptions(this IYamlTypeInfoResolver? resolver, YamlSerializerOptions options)
            => resolver is IBuiltInYamlTypeInfoResolver bir && bir.IsCompatibleWithOptions(options);
    }

    /// <summary>
    /// A <see cref="IYamlTypeInfoResolver"/> that returns null for all inputs.
    /// </summary>
    internal sealed class EmptyYamlTypeInfoResolver : IYamlTypeInfoResolver, IBuiltInYamlTypeInfoResolver
    {
        public YamlTypeInfo? GetTypeInfo(Type type, YamlSerializerOptions options) => null;
        public bool IsCompatibleWithOptions(YamlSerializerOptions _) => true;
    }

    /// <summary>
    /// Implemented by the built-in converters to avoid rooting
    /// unused resolver dependencies in the context of the trimmer.
    /// </summary>
    internal interface IBuiltInYamlTypeInfoResolver
    {
        /// <summary>
        /// Indicates whether the metadata generated by the current resolver
        /// are compatible with the run time specified <see cref="YamlSerializerOptions"/>.
        /// </summary>
        bool IsCompatibleWithOptions(YamlSerializerOptions options);
    }
}
