        [Fact]
        public void Quoting_StymlTargets_AgreeWithTheNotesExamples()
        {
            // The syntactic and resolution checks name these; the reference rules must give them.
            string[] plain = { "a", "hello world", "--port=8080", "-v", "-a b", "--", "-- a", "?x", "?x y", "-x:y", "a:b", "a#b", "a,b", "100%", "C:\\x", "a\\b", "a\"b", "a'b", "é", "1,000", "12e", "0x", "a[b" };
