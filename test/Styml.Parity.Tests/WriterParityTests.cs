        [Theory]
        [MemberData(nameof(QuotingIndexes))]
        public void Quoting_StymlTarget_FollowsTheNoteAndReadsBack(int row)
        {
            string s = WriterParityCases.Strings[row - 1];
            string target = WriterParityExpected.QuotingTargets[row - 1];
            Assert.Equal(ReferenceQuoting.Scalar(s), target);

            // Styml, both schemas: a value is a String token, a key a PropertyName, with the input's text.
            foreach (YamlSchemaKind schema in new[] { YamlSchemaKind.Core, YamlSchemaKind.Yaml11 })
            {
                var options = new YamlReaderOptions { Schema = schema };
                (YamlTokenType type, string? text) = StymlScalar("k: " + target + "\n", options, index: 1);
                Assert.Equal((YamlTokenType.String, s), (type, text));
                (type, text) = StymlScalar(target + ": v\n", options, index: 0);
                Assert.Equal((YamlTokenType.PropertyName, s), (type, text));
            }

            // YamlDotNet and SharpYaml, as parsers and as typed readers, for the strings the default and the option quote
            // alike; the strings only QuoteForLenientReaders quotes are some library's misreading, checked with the option
            // (Quoting_StymlLenientTarget_FollowsTheRuleAndReadsBack) and pinned in WriterBlockParityTests.
            if (ReferenceQuoting.IsPlain(s) != ReferenceQuoting.IsPlain(s, lenient: true))
            {
                return;
            }

            Assert.Equal(s, YdnScalars("k: " + target + "\n")[1]);
            Assert.Equal(s, YdnScalars(target + ": v\n")[0]);
            Assert.Equal(s, SyScalars("k: " + target + "\n")[1]);
            Assert.Equal(s, SyScalars(target + ": v\n")[0]);
            Assert.Equal(s, new YD.DeserializerBuilder().Build().Deserialize<Dictionary<string, string>>("k: " + target + "\n")["k"]);
            Assert.Equal(s, SY.YamlSerializer.Deserialize<Dictionary<string, string>>("k: " + target + "\n")!["k"]);
            Assert.Equal(s, new YD.DeserializerBuilder().Build().Deserialize<Dictionary<string, string>>(target + ": v\n").Keys.Single());
            if (s == "<<")
            {
                // SharpYaml's own refusal: its typed reader takes "<<" as a merge key even when quoted.
                Assert.Contains("Merge key", Assert.ThrowsAny<Exception>(() => SY.YamlSerializer.Deserialize<Dictionary<string, string>>(target + ": v\n")).Message);
            }
            else
            {
                Assert.Equal(s, SY.YamlSerializer.Deserialize<Dictionary<string, string>>(target + ": v\n")!.Keys.Single());
            }
        }

