            Dictionary<string, double> specials = YamlSerializer.Deserialize<Dictionary<string, double>>(Table1PropertyTargets[2].Yaml)!;
            Assert.True(double.IsNaN(specials["nan"]));
            Assert.Equal(double.PositiveInfinity, specials["inf"]);
            Assert.Equal(double.NegativeInfinity, specials["ninf"]);
        }

        private static string Json<T>(T value) => YamlSerializer.Serialize(value);

        private static List<(YamlTokenType, string?)> Tokens(string yaml, YamlReaderOptions options)
        {
            var reader = new Utf8YamlReader(Encoding.UTF8.GetBytes(yaml), options);
            var tokens = new List<(YamlTokenType, string?)>();
            while (reader.Read())
            {
                string? text = reader.TokenType switch
                {
                    YamlTokenType.PropertyName when reader.KeyKind == YamlKeyKind.Complex => "Complex key: " + Encoding.UTF8.GetString(reader.ValueSpan.ToArray()),
                    YamlTokenType.PropertyName or YamlTokenType.String => reader.GetString(),
                    YamlTokenType.Number or YamlTokenType.True or YamlTokenType.False or YamlTokenType.Null => Encoding.UTF8.GetString(reader.ValueSpan.ToArray()),
                    _ => null,
                };
                tokens.Add((reader.TokenType, text));
            }
            return tokens;
        }
