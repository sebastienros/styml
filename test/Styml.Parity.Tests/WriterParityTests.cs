    /// <summary>
    /// The block-style choice between plain and double-quoted for one string, as M4's quoting
    /// rules state it (decisions 2 and 2b), written for clarity, not speed. M4a's writer must agree with it
    /// on every string (the differential oracle); its resolution step is Styml's own reader.
    /// </summary>
    internal static class ReferenceQuoting
    {
        private static readonly Regex s_timestamp = new(
            @"\A(?:[0-9]{4}-[0-9]{2}-[0-9]{2}|[0-9]{4}-[0-9]{1,2}-[0-9]{1,2}(?:[Tt]|[ \t]+)[0-9]{1,2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]*)?(?:[ \t]*(?:Z|[-+][0-9]{1,2}(?::[0-9]{2})?))?)\z",
            RegexOptions.CultureInvariant);

        private static readonly Regex s_sexagesimalFloat = new(@"\A[-+]?[0-9][0-9_]*(?::[0-5]?[0-9])+\.[0-9_]*\z", RegexOptions.CultureInvariant);

        // The keywords the standards resolve that the reader's resolver does not cover: the YAML 1.1 merge and value
        // types. The booleans and nulls of both standards, in their listed cases, are the resolver's.
        private static readonly HashSet<string> s_keywords = new(StringComparer.Ordinal) { "<<", "=" };

        // QuoteForLenientReaders: decision 2's full keyword set in any case, the IEEE names among them (what no standard
        // resolves is behind the option).
        private static readonly HashSet<string> s_lenientKeywords = new(StringComparer.OrdinalIgnoreCase)
        {
            "true", "false", "null", "y", "n", "yes", "no", "on", "off",
            "nan", "inf", "+inf", "-inf", "infinity", "+infinity", "-infinity",
            "<<", "=",
        };

        private static readonly Regex s_prefixedNumber = new(@"\A[-+]?0(?:[oO][0-7]+|[xX][0-9a-fA-F]+|[bB][01]+)\z", RegexOptions.CultureInvariant);

        // The YAML 1.1 binary and hexadecimal patterns as printed match a prefix followed by underscores only, which the
        // reader's resolver does not resolve (a defect fixed in M4b).
        private static readonly Regex s_prefixWithoutDigits = new(@"\A[-+]?0[xb]_+\z", RegexOptions.CultureInvariant);

        // Ruby's Psych 3.1 (its scalar scanner), with QuoteForLenientReaders.
        private static readonly Regex s_psychSexagesimal = new(@"\A[-+]?[0-9][0-9_]*(?::[0-5]?[0-9])+\z", RegexOptions.CultureInvariant);
        private static readonly Regex s_psychDate = new(@"\A[0-9]{4}-(?:1[012]|0[0-9]|[0-9])-(?:[12][0-9]|3[01]|0[0-9]|[0-9])\z", RegexOptions.CultureInvariant);
        private static readonly Regex s_psychCommaFloat = new(@"\A[-+]?[0-9][0-9_,]*\.[0-9]*(?:[eE][-+][0-9]+)?\z", RegexOptions.CultureInvariant);
        private static readonly Regex s_psychInteger = new(@"\A[-+]?(?:0b[01]+|0[0-7]+|0|[1-9][0-9]*|0x[0-9a-fA-F]+)\z", RegexOptions.CultureInvariant);
        private static readonly Regex s_psychNoMantissa = new(@"\A[-+]?\.[eE][-+][0-9]+\z", RegexOptions.CultureInvariant);
        private static readonly Regex s_psychTime = new(@"\A-?[0-9]{4}-[0-9]{1,2}-[0-9]{1,2}(?:[Tt]|[ \t\r\f\v]+)[0-9]{1,2}:[0-9][0-9]:[0-9][0-9](?:\.[0-9]*)?(?:[ \t\r\f\v]*(?:Z|[-+][0-9]{1,2}:?(?:[0-9][0-9])?))?\z", RegexOptions.CultureInvariant);

        /// <summary>The scalar as block style writes it: the string itself, or double-quoted.</summary>
        public static string Scalar(string s, bool lenient = false) => IsPlain(s, lenient) ? s : DoubleQuoted(s);

        /// <summary>The key as block style writes it; with the option, a key with " *" is quoted too (YamlDotNet).</summary>
        public static string KeyScalar(string s, bool lenient = false) =>
            IsPlain(s, lenient) && !(lenient && s.Contains(" *", StringComparison.Ordinal)) ? s : DoubleQuoted(s);

        public static bool IsPlain(string s, bool lenient = false) => Syntactic(s) && Resolves(s) && !(lenient && LenientResolves(s));

        // What a reader that resolves beyond the standards reads as a non-string (SharpYaml drops underscores and trims
        // white space, Unicode white space included, before it parses a number, and takes any case of the keywords).
        private static bool LenientResolves(string s)
        {
            if (s_lenientKeywords.Contains(s) || (s.Length > 0 && ((s[0] > 0x7F && char.IsWhiteSpace(s[0])) || (s[^1] > 0x7F && char.IsWhiteSpace(s[^1])))))
            {
                return true;
            }

            if (PsychResolves(s))
            {
                return true;
            }

            string t = s.Replace("_", "", StringComparison.Ordinal).Trim();
            if (t.Length == 0)
            {
                return false;
            }

            bool signed = t[0] is '+' or '-';
            string u = signed ? t.Substring(1) : t;
            if (s_lenientKeywords.Contains(u) || u.Equals(".inf", StringComparison.OrdinalIgnoreCase) || u.Equals(".nan", StringComparison.OrdinalIgnoreCase)
                || s_prefixedNumber.IsMatch(t))
            {
                return true;
            }

            return (t != s || signed) && StymlNumber(t);
        }

        // Psych's sexagesimal integers with any first digit, its dates, its float with commas, its integers after it drops
        // commas and underscores (a string with a comma, starting after the sign with a digit, ',' or '_'), and its float
        // with no digit before the exponent.
        private static bool PsychResolves(string s)
        {
            if (s_psychSexagesimal.IsMatch(s) || s_psychDate.IsMatch(s) || s_psychNoMantissa.IsMatch(s) || s_psychTime.IsMatch(s))
            {
                return true;
            }

            if (!s.Contains(',', StringComparison.Ordinal))
            {
                return false;
            }

            int i = s.Length > 0 && s[0] is '+' or '-' ? 1 : 0;
            return s_psychCommaFloat.IsMatch(s)
                || (i < s.Length && (char.IsAsciiDigit(s[i]) || s[i] is ',' or '_')
                    && s_psychInteger.IsMatch(s.Replace(",", "", StringComparison.Ordinal).Replace("_", "", StringComparison.Ordinal)));
        }

        private static bool StymlNumber(string s)
        {
            var reader = new Utf8YamlReader(Encoding.UTF8.GetBytes("k: " + s + "\n"), new YamlReaderOptions { Schema = YamlSchemaKind.Yaml11 });
            try
            {
                reader.Read();
                reader.Read();
                reader.Read();
                return reader.TokenType == YamlTokenType.Number;
            }
            catch (YamlException)
            {
                return false;
            }
        }

        private static bool Syntactic(string s)
        {
            if (s.Length == 0)
            {
                return false;
            }
            char first = s[0];
            if ("-?:,[]{}#&*!|>'\"%@`".IndexOf(first) >= 0)
            {
                bool dashOrQuestion = first is '-' or '?';
                if (!dashOrQuestion || s.Length == 1 || s[1] is ' ' or '\t')
                {
                    return false;
                }
            }
            if (first is ' ' or '\t' || s[^1] is ' ' or '\t' || s.Contains('\t'))
            {
                return false;
            }
            if (s.Contains(": ", StringComparison.Ordinal) || s.EndsWith(':') || s.Contains(" #", StringComparison.Ordinal))
            {
                return false;
            }
            if (s.StartsWith("---", StringComparison.Ordinal) || s.StartsWith("...", StringComparison.Ordinal))
            {
                return false;
            }
            for (int i = 0; i < s.Length; i++)
            {
                if (MustEscape(s[i]) || char.IsSurrogate(s[i]) && !(char.IsHighSurrogate(s[i]) && i + 1 < s.Length && char.IsLowSurrogate(s[++i])))
                {
                    return false;
                }
            }
            return true;
        }

        // The YAML escape set without '"' and '\', which need escaping only between double quotes; line breaks
        // (LF, CR, NEL, LS, PS) are in it.
        private static bool MustEscape(char c) => c < 0x20 || c == 0x7F || (c >= 0x80 && c <= 0x9F) || c is '\u2028' or '\u2029' or '\ufeff';

        private static bool Resolves(string s)
        {
            if (s_keywords.Contains(s) || s_timestamp.IsMatch(s) || s_sexagesimalFloat.IsMatch(s) || s_prefixWithoutDigits.IsMatch(s))
            {
                return false;
            }
            foreach (YamlSchemaKind schema in new[] { YamlSchemaKind.Core, YamlSchemaKind.Yaml11 })
            {
                var reader = new Utf8YamlReader(Encoding.UTF8.GetBytes("k: " + s + "\n"), new YamlReaderOptions { Schema = schema });
                reader.Read();
                reader.Read();
                reader.Read();
                if (reader.TokenType != YamlTokenType.String || reader.GetString() != s)
                {
                    return false;
                }
            }
            return true;
        }

        private static string DoubleQuoted(string s)
        {
            var sb = new StringBuilder("\"");
            foreach (char c in s)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\b': sb.Append("\\b"); break;
                    case '\f': sb.Append("\\f"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (MustEscape(c))
                        {
                            sb.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            sb.Append(c);
                        }
                        break;
                }
            }
            return sb.Append('"').ToString();
        }
    }
