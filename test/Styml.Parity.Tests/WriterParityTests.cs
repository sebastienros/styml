        [Fact]
        public void Table1_StymlTargetsWithProperties_Read()
        {
            List<(YamlTokenType, string?)> key = Tokens(Table1PropertyTargets[0].Yaml, default);
            Assert.Equal(new (YamlTokenType, string?)[] { (YamlTokenType.StartObject, null), (YamlTokenType.PropertyName, "Complex key: V: 2"), (YamlTokenType.Number, "1"), (YamlTokenType.EndObject, null) }, key);

