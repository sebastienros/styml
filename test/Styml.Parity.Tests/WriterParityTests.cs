        private static (YamlTokenType, string?) StymlScalar(string yaml, YamlReaderOptions options, int index)
        {
            var reader = new Utf8YamlReader(Encoding.UTF8.GetBytes(yaml), options);
            int i = 0;
            while (reader.Read())
            {
                if (reader.TokenType is YamlTokenType.StartObject or YamlTokenType.EndObject or YamlTokenType.StartArray or YamlTokenType.EndArray)
                {
                    continue;
                }
                if (i++ == index)
                {
                    return (reader.TokenType, reader.GetString());
                }
            }
            throw new InvalidOperationException("no scalar " + index + " in " + yaml);
        }

        private static List<string> YdnScalars(string yaml)
        {
            var parser = new YDCore.Parser(new StringReader(yaml));
            var scalars = new List<string>();
            while (parser.MoveNext())
            {
                if (parser.Current is YDEvents.Scalar scalar)
                {
                    scalars.Add(scalar.Value);
                }
            }
            return scalars;
        }

        private static List<string> SyScalars(string yaml)
        {
            SY.IParser parser = SY.Parser.CreateParser(new StringReader(yaml));
            var scalars = new List<string>();
            while (parser.MoveNext())
            {
                if (parser.Current is SYE.Scalar scalar)
                {
                    scalars.Add(scalar.Value);
                }
            }
            return scalars;
        }

